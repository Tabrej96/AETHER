function generateRealtime(productSpec: ProductSpec, domain: DomainPack): string {
  return `/**
 * AETHER-generated realtime WebSocket server
 * Features: ${domain.realtime.features.join(', ')}
 */

import { WebSocketServer, WebSocket } from 'ws';

export function createWebSocketServer(db: any, config: any) {
  const wss = new WebSocketServer({ port: 3001 });

  const clients = new Map<string, WebSocket>();

  wss.on('connection', (ws, req) => {
    const memberId = new URL(req.url ?? '', 'http://localhost').searchParams.get('memberId') ?? 'anonymous';
    clients.set(memberId, ws);

    ws.on('message', (data) => {
      try {
        const message = JSON.parse(data.toString());
        // Broadcast to relevant clients
        for (const [id, client] of clients) {
          if (client.readyState === WebSocket.OPEN) {
            client.send(JSON.stringify({ from: memberId, ...message }));
          }
        }
      } catch {
        // ignore malformed messages
      }
    });

    ws.on('close', () => {
      clients.delete(memberId);
    });
  });

  return wss;
}
`;
}

